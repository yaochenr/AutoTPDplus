#!/usr/bin/env python3

from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[2]
DEFAULT_CONFIG = REPO / "tpd_curator" / "config" / "monthly_update_workflow.yaml"


def git(*args: str, check: bool = True) -> subprocess.CompletedProcess:
    return subprocess.run(["git", *args], cwd=REPO, check=check, capture_output=True, text=True)


def gh(*args: str, check: bool = True) -> subprocess.CompletedProcess:
    return subprocess.run(["gh", *args], cwd=REPO, check=check, capture_output=True, text=True)


def output_paths(config: dict, month: str) -> list[str]:
    paths = config["paths"]
    candidates = [
        f"{paths['updates_root']}/{month}",
        paths["state"],
        paths["retired_ids"],
        *paths["release"].values(),
        "scripts/data_standardization.py",
    ]
    return [p for p in candidates if (REPO / p).exists()]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Commit the monthly update and open a Draft PR.")
    parser.add_argument("--month", required=True)
    parser.add_argument("--config", type=Path, default=DEFAULT_CONFIG)
    parser.add_argument("--no_push", action="store_true", help="Commit locally only.")
    args = parser.parse_args(argv)

    config = yaml.safe_load(args.config.read_text(encoding="utf-8"))
    git_cfg = config["git"]
    branch = f"{git_cfg['branch_prefix']}{args.month}"
    summary = REPO / config["paths"]["updates_root"] / args.month / "workflow_summary.md"
    if not summary.exists():
        print(f"Error: {summary} not found; run scripts/monthly/run_monthly_workflow.py first.")
        return 1

    current = git("rev-parse", "--abbrev-ref", "HEAD").stdout.strip()
    if current != branch:
        if git("rev-parse", "--verify", "--quiet", f"refs/heads/{branch}", check=False).returncode == 0:
            print(f"Error: branch {branch} exists but {current} is checked out.")
            return 1
        git("switch", "-c", branch)

    git("add", "--", *output_paths(config, args.month))
    if git("diff", "--cached", "--quiet", check=False).returncode != 0:
        git("commit", "-m", f"Monthly AutoTPD+ update {args.month}",
            "-m", f"Generated by scripts/monthly/run_monthly_workflow.py. See "
                  f"{config['paths']['updates_root']}/{args.month}/workflow_summary.md.")
        print(f"Committed on {branch}")
    else:
        print("Nothing new to commit")

    if args.no_push:
        return 0
    git("push", "-u", git_cfg["remote"], branch)
    title = f"Monthly AutoTPD+ update {args.month}"
    if gh("pr", "view", branch, "--json", "number", check=False).returncode == 0:
        gh("pr", "edit", branch, "--body-file", str(summary))
        print(f"Updated PR for {branch}")
    else:
        created = gh("pr", "create", "--draft", "--base", git_cfg["base_branch"], "--head", branch,
                     "--title", title, "--body-file", str(summary))
        print(created.stdout.strip())
    return 0

if __name__ == "__main__":
    try:
        sys.exit(main())
    except subprocess.CalledProcessError as exc:
        print(f"Error: {' '.join(exc.cmd)} failed:\n{exc.stderr}")
        sys.exit(1)
